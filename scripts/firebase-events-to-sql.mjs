#!/usr/bin/env node
// One-off migration: calendar events from the old Firebase Realtime Database
// (Handlingslista app) into Supabase.
//
// Usage:
//   node scripts/firebase-events-to-sql.mjs <firebase-backup.json> > events.sql
//   supabase db query --linked -f events.sql
//
// The backup itself holds personal data and is never committed.
//
// Old shape:  events/{key} = { date: "2026-10-16", time: "13:30" | null, title, person, createdAt }
// person:     "Alexander" | "Alexandra" | "Båda"
// New shape:  public.events (household_id, title, date, time, assigned_to → members.id)

import { readFileSync } from "node:fs";

const HOUSEHOLD = "CANCINOS"; // households.name
// Old person → members.display_name in the new app. "Båda" (both) = no one = shared.
const PEOPLE = { Alexander: "FADER", Alexandra: "MODER" };

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/firebase-events-to-sql.mjs <firebase-backup.json>");
  process.exit(1);
}

const backup = JSON.parse(readFileSync(file, "utf8"));
const events = Object.values(backup.events ?? {});

const quote = (value) => (value == null || value === "" ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const isDate = (value) => /^\d{4}-\d{2}-\d{2}$/.test(value ?? "");
const isTime = (value) => /^\d{2}:\d{2}$/.test(value ?? "");

const household = `(select id from public.households where name = ${quote(HOUSEHOLD)})`;
const member = (person) =>
  PEOPLE[person]
    ? `(select id from public.members where household_id = ${household} and display_name = ${quote(PEOPLE[person])})`
    : "null";

const rows = events.filter((e) => e.title && isDate(e.date));
const skipped = events.length - rows.length;

console.log("-- Generated by scripts/firebase-events-to-sql.mjs");
console.log(`-- ${rows.length} events, ${skipped} skipped (missing title or date)`);
console.log("begin;");
for (const e of rows) {
  const time = isTime(e.time) ? quote(e.time) : "null";
  // Skip events that already exist, so running the script twice is safe
  console.log(`insert into public.events (household_id, title, date, time, assigned_to)
select ${household}, ${quote(e.title)}, ${quote(e.date)}, ${time}, ${member(e.person)}
where not exists (
  select 1 from public.events
  where household_id = ${household} and title = ${quote(e.title)} and date = ${quote(e.date)}
    and time is not distinct from ${time}::time
);`);
}
console.log("commit;");
